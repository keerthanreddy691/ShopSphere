import { Link } from 'react-router-dom';
import { useQuery } from '@tanstack/react-query';
import {
  IndianRupee,
  ShoppingBag,
  Package,
  AlertTriangle,
  RotateCcw,
  BadgePercent,
  Plus,
  ArrowRight,
  TrendingUp,
  Store,
} from 'lucide-react';
import { ResponsiveContainer, AreaChart, Area, XAxis, YAxis, Tooltip, CartesianGrid } from 'recharts';
import { get } from '@/lib/api';
import { KpiCard } from '@/components/common/KpiCard';
import { Button } from '@/components/ui/button';
import { Card } from '@/components/ui/card';
import { Skeleton } from '@/components/ui/skeleton';
import { StatusBadge } from '@/components/common/StatusBadge';
import { ErrorState } from '@/components/common/ErrorState';
import { formatPrice, formatDateTime } from '@/lib/format';

export default function SellerOverviewPage() {
  const { data, isLoading, isError, error, refetch } = useQuery({
    queryKey: ['seller-overview'],
    queryFn: () => get('/sellers/me/overview'),
  });

  if (isLoading) {
    return (
      <div className="space-y-6">
        <Skeleton className="h-8 w-48" />
        <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
          {[1, 2, 3, 4, 5, 6].map((i) => (
            <Skeleton key={i} className="h-28 rounded-2xl" />
          ))}
        </div>
        <Skeleton className="h-80 rounded-2xl" />
      </div>
    );
  }

  if (isError) return <ErrorState error={error} onRetry={refetch} />;

  const trend = data?.salesTrend || [];

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl font-bold">Seller Dashboard</h1>
          <p className="mt-1 text-sm text-ink-muted">Monitor your store revenue, fulfill incoming orders, and track payouts.</p>
        </div>
        <div className="flex gap-2">
          <Link to="/seller/products/new">
            <Button className="gap-2">
              <Plus className="size-4" /> Add Product
            </Button>
          </Link>
        </div>
      </div>

      {/* KPI Cards */}
      <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
        <KpiCard
          label="Total Revenue"
          value={formatPrice(data.revenue)}
          hint="Net earnings after platform fees"
          icon={IndianRupee}
          tone="brand"
        />
        <KpiCard
          label="Total Orders"
          value={data.orders}
          hint={`${data.orderCounts?.DELIVERED || 0} delivered`}
          icon={ShoppingBag}
          tone="green"
        />
        <KpiCard
          label="Active Products"
          value={data.products}
          hint="Listed in catalog"
          icon={Package}
          tone="sky"
        />
        <KpiCard
          label="Low Stock Alerts"
          value={data.lowStock}
          hint="Items below threshold"
          icon={AlertTriangle}
          tone={data.lowStock > 0 ? 'orange' : 'brand'}
        />
        <KpiCard
          label="Pending Returns"
          value={data.pendingReturns}
          hint="Requests awaiting review"
          icon={RotateCcw}
          tone={data.pendingReturns > 0 ? 'amber' : 'brand'}
        />
        <KpiCard
          label="Pending Settlement"
          value={formatPrice(data.settlementAmount)}
          hint="Queued for payout"
          icon={BadgePercent}
          tone="violet"
        />
      </div>

      {/* Sales Trend Chart */}
      <Card className="p-5 sm:p-6">
        <div className="mb-4 flex items-center justify-between">
          <div>
            <h2 className="flex items-center gap-2 text-base font-semibold">
              <TrendingUp className="size-5 text-brand-600" /> 7-Day Revenue Trend
            </h2>
            <p className="text-xs text-ink-muted">Gross daily sales generated by your store</p>
          </div>
        </div>
        <div className="h-72 w-full">
          <ResponsiveContainer width="100%" height="100%">
            <AreaChart data={trend} margin={{ top: 10, right: 10, left: 0, bottom: 0 }}>
              <defs>
                <linearGradient id="sellerSalesGrad" x1="0" y1="0" x2="0" y2="1">
                  <stop offset="5%" stopColor="#2563eb" stopOpacity={0.25} />
                  <stop offset="95%" stopColor="#2563eb" stopOpacity={0.0} />
                </linearGradient>
              </defs>
              <CartesianGrid strokeDasharray="3 3" vertical={false} stroke="#e2e8f0" />
              <XAxis dataKey="date" tick={{ fontSize: 12, fill: '#64748b' }} stroke="#cbd5e1" />
              <YAxis tick={{ fontSize: 12, fill: '#64748b' }} stroke="#cbd5e1" tickFormatter={(v) => `₹${v}`} />
              <Tooltip
                formatter={(val) => [formatPrice(val), 'Sales']}
                contentStyle={{ borderRadius: '12px', border: '1px solid #e2e8f0', boxShadow: '0 4px 12px rgba(0,0,0,0.05)' }}
              />
              <Area type="monotone" dataKey="sales" stroke="#2563eb" strokeWidth={2.5} fillOpacity={1} fill="url(#sellerSalesGrad)" />
            </AreaChart>
          </ResponsiveContainer>
        </div>
      </Card>

      {/* Recent Orders */}
      <Card className="overflow-hidden">
        <div className="flex items-center justify-between border-b border-slate-100 bg-slate-50/70 px-5 py-4">
          <h2 className="text-base font-semibold">Recent Store Orders</h2>
          <Link to="/seller/orders" className="text-xs font-semibold text-brand-600 hover:underline">
            View all orders →
          </Link>
        </div>

        {!data.recentOrders?.length ? (
          <p className="p-8 text-center text-sm text-ink-muted">No orders received yet.</p>
        ) : (
          <div className="divide-y divide-slate-100">
            {data.recentOrders.map((o) => (
              <div key={o._id} className="flex flex-wrap items-center justify-between gap-4 p-4 transition hover:bg-slate-50 sm:px-5">
                <div>
                  <div className="flex items-center gap-2">
                    <span className="font-mono text-sm font-bold text-ink">{o.orderNumber}</span>
                    <StatusBadge status={o.status} />
                  </div>
                  <p className="mt-1 text-xs text-ink-muted">
                    Customer: {o.customer?.name} · {formatDateTime(o.createdAt)}
                  </p>
                </div>
                <div className="flex items-center gap-4">
                  <div className="text-right">
                    <p className="text-sm font-bold">{formatPrice(o.total)}</p>
                    <p className="text-[11px] text-ink-muted">{o.itemCount} items</p>
                  </div>
                  <Link to={`/seller/orders`}>
                    <Button variant="outline" size="sm">
                      Manage <ArrowRight className="size-3.5" />
                    </Button>
                  </Link>
                </div>
              </div>
            ))}
          </div>
        )}
      </Card>
    </div>
  );
}

